#returns two new genomes produced by crossing over the given genomes at a random crossover point.
def crossover(genome1, genome2): 
    assert len(genome1) == len(genome2), "mismatched genome lengths"
    cross = random.randint(1, len(genome1) - 1)
    cross1 = genome1[:cross] + genome2[cross:]
    cross2 = genome2[:cross] + genome1[cross:]
    return cross1, cross2 

#returns a new mutated version of the given genome.
def mutate(genome, mutation_rate): 
    new = []
    for genes in genome: 
        if random.random() < mutation_rate: 
            new.append("1" if genes == 0 else "0")
        else: 
            new.append(genes)
    return "".join(new)
    
# selects and returns two genomes from the given population using fitness-proportionate selection. 
# This function should use weighted_choice, which we wrote in class, as a helper function.
def select_pair(population): 
    weights = [fitness(gene) for gene in population]
    gene1 = weighted_choice(population, weights)
    gene2 = weighted_choice(population, weights)
    return gene1, gene2



def weighted_choice(elements, weights):
        assert len(elements) == len(weights), "mismatched list lengths"
        for w in weights:
            assert w >= 0, "negative weights not allowed" 
        total = sum(weights)
        choice = random.uniform(0,total)
        current = 0
        for i in range(0, len(elements)):
            current += weights[i]
            if current > choice:
                return elements[i]

