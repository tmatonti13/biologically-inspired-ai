#is the main GA program, which takes the population size, crossover rate (pc), and mutation rate (pm) as parameters. 
#The optional logfile parameter is a string specifying the name of a text file in which to 
#store the data generated by the GA, for plotting purposes. When the GA terminates, 
# this function should return the generation number at which the string of all ones was found.

genome_length = 20

def main(population_size, crossover_rate, mutation_rate, logfile=""):
    print(f"population size: {population_size}")
    print(f"Genome length: {genome_length}")

    population = make_population(population_size, genome_length)
    
    for i in range(50): 
        new_population = []
        while len(new_population) < len(population): 
            p1, p2 = select_pair(population)
            if random.random() < crossover_rate: 
                 p1, p2 = crossover(p1, p2) 

            p1 = mutate(p1, mutation_rate)
            p2 = mutate(p2, mutation_rate)
            new_population.append(p1)
            new_population.append(p2)

        population = new_population
        avg, best = evaluate_fitness(population)
        print(f"Generation {i}: average fitness {avg}, best fitness {best}")
        if logfile != "":
            with open(logfile, "a") as f:
                f.write(f"{i} {avg} {best} \n")  
        if best == genome_length: 
            return i 
    return 49
        
