def random_genome(length):
# returns a random genome (bit string) of a given length.
    genome = "" 
    for i in range(length):
        genome += str(random.choice('01'))
    return genome

def make_population(size, length): 
    # returns a new randomly created population of the specified size, 
    # represented as a list of genomes of the specified length.
    population = [] 
    for i in range(size): 
        genome = random_genome(length) 
        population.append(genome)
    return population


def fitness(genome): 
# returns the fitness value of a genome
    return genome.count("1")    

def evaluate_fitness(population): 
# returns a pair of values: the average fitness 
# of the population as a whole and the fitness of the best individual in the population.
    total_fitness = 0
    best_fitness = 0
    for genome in population:
        count = fitness(genome)
        total_fitness += count
        if count > best_fitness:
            best_fitness = count
    avg_fitness = total_fitness / len(population)
    return avg_fitness, best_fitness 


